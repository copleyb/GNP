"""
compiler.py — Prompt Compiler.

Takes a PanelSpec and produces a GenerationRequest — the fully assembled
payload for the Image Generation Backend.

Layer assembly order (fixed):
  [1] Style identity tokens
  [2] Shot type + mood tokens
  [3] Environment identity tokens
  [4] Character identity tokens
  [5] Scene prompt (LLM-generated by Scene Prompt Generator)
  [6] Negative / exclusion tokens (deduplicated)
  [7] Negative space directive (optional, deterministic from panel_seed)
  [8] Reference image descriptions (deterministic from selection metadata)

Layers [1–4] and [6–8] are deterministic. Layer [5] is an LLM call.

Per DESIGN.md §13.5: Returns structured data, no print() statements, no CLI logic.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml


class ScenePromptError(Exception):
    """Raised when the Scene Prompt Generator LLM call fails."""
    pass


# -- Result types ------------------------------------------------------------

@dataclass(frozen=True)
class ReferenceSelection:
    """A selected reference image and its role assignment."""
    ref_id: str
    file: str
    role: str  # "character" or "environment"
    character_id: str | None = None
    environment_id: str | None = None
    purpose: str = ""
    priority: int = 999
    display_name: str = ""


@dataclass(frozen=True)
class GenerationRequest:
    """
    Fully assembled payload for the Image Generation Backend.

    The Backend Adapter receives this object and makes the API call.
    It needs no additional context — everything is embedded here.
    """
    panel_id: str
    model: str
    prompt: str
    size: str  # "1024x1024" | "1536x1024" | "1024x1536"
    quality: str
    thinking: str
    seed: int | None
    reference_images: list[dict[str, str]]
    panelspec_path: str
    compiler_version: str
    # Internal metadata (not sent to API, stored in Generation Record)
    _scene_prompt: str = ""
    _reference_selections: list[ReferenceSelection] = field(default_factory=list)
    _context_profile: str = ""

    def to_dict(self) -> dict[str, Any]:
        """Serialise for the Provenance Store (includes internal metadata)."""
        return {
            "panel_id": self.panel_id,
            "model": self.model,
            "prompt": self.prompt,
            "size": self.size,
            "quality": self.quality,
            "thinking": self.thinking,
            "seed": self.seed,
            "reference_images": self.reference_images,
            "panelspec_path": self.panelspec_path,
            "compiler_version": self.compiler_version,
            "_scene_prompt": self._scene_prompt,
            "_reference_selections": [
                {
                    "ref_id": s.ref_id,
                    "file": s.file,
                    "role": s.role,
                    "character_id": s.character_id,
                    "environment_id": s.environment_id,
                    "purpose": s.purpose,
                    "priority": s.priority,
                    "display_name": s.display_name,
                }
                for s in self._reference_selections
            ],
            "_context_profile": self._context_profile,
        }


# -- Aspect ratio selector ---------------------------------------------------

# gpt-image-2 supported sizes and their aspect ratios
_SUPPORTED_SIZES = [
    ("1024x1024", 1.0),
    ("1536x1024", 1.5),    # landscape
    ("1024x1536", 0.667),  # portrait
]


def select_aspect_ratio(width_px: int, height_px: int) -> str:
    """
    Select the closest supported gpt-image-2 size for the given panel geometry.

    Returns one of "1024x1024", "1536x1024", "1024x1536".
    """
    target_ratio = width_px / height_px
    best = min(_SUPPORTED_SIZES, key=lambda s: abs(s[1] - target_ratio))
    return best[0]


# -- Reference image budget allocation ---------------------------------------

def allocate_reference_budget(
    characters: list[dict[str, Any]],
    environment: dict[str, Any] | None,
    budget: int,
) -> dict[str, list[dict[str, Any]]]:
    """
    Allocate the reference image budget across characters and environment.

    Strategy: proportional with guaranteed minimums.
    - Each character: guaranteed 1 slot.
    - Environment: guaranteed 1 slot if it has references.
    - Remaining slots distributed equally among characters, rounded down.
    - Leftover slots go to the primary character (first in array).
    - Underfill: unused slots are NOT redistributed.

    Returns a dict keyed by "character:{id}" or "environment:{id}",
    each containing the list of selected reference dicts.
    """
    char_count = len(characters)
    env_has_refs = environment is not None and len(environment.get("references", [])) > 0

    # Guaranteed minimums
    char_min = 1 if char_count > 0 else 0
    env_min = 1 if env_has_refs else 0
    guaranteed = char_count * char_min + env_min

    if guaranteed > budget:
        # Budget too small for full guarantees — give each character 1,
        # then environment if anything left.
        result: dict[str, list[dict[str, Any]]] = {}
        remaining = budget
        for char in characters:
            if remaining <= 0:
                break
            refs = sorted(char.get("references", []), key=lambda r: r.get("priority", 999))
            if refs:
                result[f"character:{char['character_id']}"] = [refs[0]]
                remaining -= 1
        if env_has_refs and remaining > 0:
            refs = sorted(environment["references"], key=lambda r: r.get("priority", 999))
            result[f"environment:{environment['environment_id']}"] = [refs[0]]
        return result

    remaining = budget - guaranteed

    # Distribute remaining slots equally among characters, rounded down
    extra_per_char = remaining // char_count if char_count > 0 else 0
    leftover = remaining - (extra_per_char * char_count)

    result = {}
    for i, char in enumerate(characters):
        allocation = char_min + extra_per_char
        # Primary character gets leftover
        if i == 0:
            allocation += leftover
        refs = sorted(char.get("references", []), key=lambda r: r.get("priority", 999))
        selected = refs[:allocation]
        if selected:
            result[f"character:{char['character_id']}"] = selected

    if env_has_refs:
        refs = sorted(environment["references"], key=lambda r: r.get("priority", 999))
        selected = refs[:env_min]
        if selected:
            result[f"environment:{environment['environment_id']}"] = selected

    return result


# -- Scene Prompt Generator --------------------------------------------------

class ScenePromptGenerator:
    """
    Sub-component of the Prompt Compiler.

    Translates the brief Chapter Plan panel description into a detailed,
    composable scene narrative suitable for image generation.

    Uses GPT-4o-mini (configurable via project.yaml).
    Stateles — each panel gets a fresh call with no memory.
    """

    def __init__(self, model: str, context_profile: str):
        self.model = model
        self.context_profile = context_profile

    def _build_system_prompt(self) -> str:
        return (
            "You are a scene prompt writer for a graphic novel production pipeline. "
            "Your job is to expand a brief panel description into a detailed, vivid scene "
            "description suitable for an AI image generator. "
            "Write in second person present tense (\"We see...\"). "
            "Focus on visual composition, lighting, character poses, and atmosphere. "
            "Do not describe text, speech bubbles, or lettering. "
            "Do not invent new characters or environments. "
            "Keep the description to 2-4 sentences. Be concrete and specific."
        )

    def _build_user_prompt(
        self,
        panel_spec: dict[str, Any],
        surrounding_descriptions: list[str] | None = None,
        user_feedback: str | None = None,
    ) -> str:
        parts: list[str] = []

        # Style tokens (layers 1-4 assembled)
        style = panel_spec.get("style", {})
        vs = style.get("visual_style", {})
        parts.append(f"Visual style: {vs.get('prompt_tokens', '')}")
        parts.append(f"Lighting: {style.get('lighting_defaults', '')}")

        # Shot type and mood
        parts.append(f"Shot type: {panel_spec.get('shot_type', '')}")
        parts.append(f"Mood: {panel_spec.get('mood', '')}")

        # Environment
        env = panel_spec.get("environment")
        if env:
            parts.append(f"Environment: {env.get('prompt_tokens', {}).get('identity', '')}")

        # Characters
        for char in panel_spec.get("characters", []):
            tokens = char.get("prompt_tokens", {})
            identity = tokens.get("identity", "")
            parts.append(f"Character {char.get('display_name', '')}: {identity}")

        # Continuity
        cont = panel_spec.get("continuity", {})
        if cont:
            parts.append(f"Time of day: {cont.get('time_of_day', '')}")
            parts.append(f"Location: {cont.get('location', '')}")

        # Continuity narrative (per-panel storyboard entry from the scene)
        continuity_narrative = panel_spec.get("continuity_narrative")
        if continuity_narrative:
            parts.append(f"\nContinuity narrative (visual storyboard for this panel): {continuity_narrative}")

        # Panel description (the core input)
        parts.append(f"\nPanel description: {panel_spec.get('description', '')}")

        # Surrounding panels for continuity
        if surrounding_descriptions:
            parts.append("\nSurrounding panels for context:")
            for desc in surrounding_descriptions:
                parts.append(f"  - {desc}")

        # User feedback (highest priority on regeneration)
        if user_feedback:
            parts.append(f"\nDIRECTOR'S NOTE (overrides all other instructions): {user_feedback}")

        return "\n".join(parts)

    def generate(
        self,
        panel_spec: dict[str, Any],
        surrounding_descriptions: list[str] | None = None,
        user_feedback: str | None = None,
        call_llm: Any = None,
    ) -> str:
        """
        Generate the scene prompt for a single panel.

        Args:
            panel_spec: The PanelSpec dict.
            surrounding_descriptions: Brief descriptions of adjacent panels.
            user_feedback: Optional human override instruction.
            call_llm: Callable (model, system_prompt, user_prompt) -> str.
                      If None, uses the real OpenAI API.

        Returns:
            The scene prompt string (layer [5]).
        """
        system_prompt = self._build_system_prompt()
        user_prompt = self._build_user_prompt(
            panel_spec, surrounding_descriptions, user_feedback
        )

        if call_llm is not None:
            return call_llm(self.model, system_prompt, user_prompt)

        return self._call_openai(system_prompt, user_prompt)

    def _call_openai(self, system_prompt: str, user_prompt: str) -> str:
        """Make the actual OpenAI API call."""
        from openai import OpenAI

        client = OpenAI()
        try:
            response = client.chat.completions.create(
                model=self.model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=0.7,
            )
            return response.choices[0].message.content.strip()
        except Exception as e:
            raise ScenePromptError(f"Scene prompt generation failed: {e}") from e


