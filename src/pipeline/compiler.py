# -- Prompt Compiler ---------------------------------------------------------

class PromptCompiler:
    """
    Compiles a PanelSpec into a GenerationRequest.

    Assembles the prompt in the fixed six-layer order (plus reference
    descriptions as layer [8]). Handles reference image selection and
    budget allocation, negative space injection, and aspect ratio selection.
    """

    def __init__(self, config: Any):
        """
        Initialise the Compiler with project configuration.

        Args:
            config: ProjectConfig from pipeline.config.load_config.
        """
        self.config = config
        self.scene_prompt_generator = ScenePromptGenerator(
            model=config.scene_prompt.model,
            context_profile=config.scene_prompt.context_profile,
        )
        self.context_store = SceneContextStore()

    # -- Layer assembly (deterministic) --------------------------------------

    def _layer_style(self, panel_spec: dict[str, Any]) -> str:
        """Layer [1]: Style identity tokens."""
        style = panel_spec["style"]
        vs = style["visual_style"]
        parts = [vs.get("prompt_tokens", "").strip()]
        if vs.get("color_palette"):
            parts.append(vs["color_palette"].strip())
        if vs.get("line_weight"):
            parts.append(vs["line_weight"].strip())
        if vs.get("shading_approach"):
            parts.append(vs["shading_approach"].strip())
        return ". ".join(p for p in parts if p)

    def _layer_shot_mood(self, panel_spec: dict[str, Any]) -> str:
        """Layer [2]: Shot type + mood tokens."""
        shot = panel_spec.get("shot_type", "")
        mood = panel_spec.get("mood", "")
        parts = []
        if shot:
            parts.append(f"Shot: {shot}")
        if mood:
            parts.append(f"Mood: {mood}")
        return ", ".join(parts)

    def _layer_environment(self, panel_spec: dict[str, Any]) -> str:
        """Layer [3]: Environment identity tokens."""
        env = panel_spec.get("environment")
        if not env:
            return ""
        tokens = env.get("prompt_tokens", {})
        parts = [tokens.get("identity", "").strip()]
        return ". ".join(p for p in parts if p)

    def _layer_characters(self, panel_spec: dict[str, Any]) -> str:
        """Layer [4]: Character identity tokens (in array order)."""
        chars = panel_spec.get("characters", [])
        if not chars:
            return ""
        parts = []
        for char in chars:
            tokens = char.get("prompt_tokens", {})
            identity = tokens.get("identity", "").strip()
            costume = char.get("costume", {}).get("default", "").strip()
            if costume:
                parts.append(f"{identity}. Currently wearing: {costume}")
            else:
                parts.append(identity)
        return ". ".join(p for p in parts if p)

    def _layer_exclusions(self, panel_spec: dict[str, Any]) -> str:
        """Layer [6]: Negative/exclusion tokens (deduplicated)."""
        all_exclusions: list[str] = []

        # Style forbidden elements
        style = panel_spec.get("style", {})
        all_exclusions.extend(style.get("forbidden_elements", []))

        # Environment exclusions
        env = panel_spec.get("environment")
        if env:
            all_exclusions.extend(
                env.get("prompt_tokens", {}).get("exclusions", [])
            )

        # Character exclusions
        for char in panel_spec.get("characters", []):
            all_exclusions.extend(
                char.get("prompt_tokens", {}).get("exclusions", [])
            )

        # Deduplicate while preserving order
        seen: set[str] = set()
        unique: list[str] = []
        for ex in all_exclusions:
            if ex not in seen:
                seen.add(ex)
                unique.append(ex)

        return ", ".join(unique)

    def _layer_negative_space(self, panel_spec: dict[str, Any]) -> str:
        """Layer [7]: Negative space directive (deterministic from panel_seed)."""
        seed = panel_spec.get("panel_seed", "00")
        # Even hex byte → inject; odd → do not inject
        try:
            seed_value = int(seed, 16)
        except ValueError:
            return ""

        if seed_value % 2 == 0:
            return (
                "This composition should include relatively unused area of low detail where a speech bubble will eventually be added. "
                "Don't draw the bubble, just compose the image so an editor can add it later."
            )
        return ""

    def _layer_reference_descriptions(
        self,
        selections: dict[str, list[dict[str, Any]]],
    ) -> str:
        """Layer [8]: Reference image descriptions (deterministic)."""
        if not selections:
            return ""

        lines: list[str] = []
        index = 1
        for key, refs in selections.items():
            if key.startswith("character:"):
                char_id = key.split(":", 1)[1]
                for ref in refs:
                    purpose = ref.get("purpose", "reference")
                    display = ref.get("display_name", char_id)
                    # Convert purpose enum to readable text
                    purpose_text = purpose.replace("_", " ")
                    costume = ref.get("costume", "default")
                    lines.append(
                        f"Reference image {index}: {display}, "
                        f"{purpose_text} reference, {costume} costume."
                    )
                    index += 1
            elif key.startswith("environment:"):
                env_id = key.split(":", 1)[1]
                for ref in refs:
                    purpose = ref.get("purpose", "establishing_shot")
                    display = ref.get("display_name", env_id)
                    purpose_text = purpose.replace("_", " ")
                    lines.append(
                        f"Reference image {index}: {display}, "
                        f"{purpose_text} reference."
                    )
                    index += 1

        return "\n".join(lines)

    # -- Reference image selection -------------------------------------------

    def _select_references(
        self,
        panel_spec: dict[str, Any],
    ) -> tuple[dict[str, list[dict[str, Any]]], list[ReferenceSelection]]:
        """
        Select reference images within the budget and build selection records.

        Returns:
            (selections_dict, selection_records) where selections_dict maps
            "character:{id}"/"environment:{id}" → list of ref dicts (with
            display_name added), and selection_records is a list of
            ReferenceSelection objects.
        """
        budget = self.config.image_generation.reference_budget

        # Enrich references with display_name for the description layer
        characters = []
        for char in panel_spec.get("characters", []):
            enriched = dict(char)
            enriched_refs = []
            for ref in char.get("references", []):
                r = dict(ref)
                r["display_name"] = char.get("display_name", char["character_id"])
                enriched_refs.append(r)
            enriched["references"] = enriched_refs
            characters.append(enriched)

        environment = None
        env_data = panel_spec.get("environment")
        if env_data:
            environment = dict(env_data)
            env_refs = []
            for ref in env_data.get("references", []):
                r = dict(ref)
                r["display_name"] = env_data.get("display_name", env_data["environment_id"])
                env_refs.append(r)
            environment["references"] = env_refs

        selections = allocate_reference_budget(characters, environment, budget)

        # Build ReferenceSelection records
        selection_records: list[ReferenceSelection] = []
        for key, refs in selections.items():
            if key.startswith("character:"):
                char_id = key.split(":", 1)[1]
                for ref in refs:
                    selection_records.append(ReferenceSelection(
                        ref_id=ref["ref_id"],
                        file=ref["file"],
                        role="character",
                        character_id=char_id,
                        purpose=ref.get("purpose", ""),
                        priority=ref.get("priority", 999),
                        display_name=ref.get("display_name", char_id),
                    ))
            elif key.startswith("environment:"):
                env_id = key.split(":", 1)[1]
                for ref in refs:
                    selection_records.append(ReferenceSelection(
                        ref_id=ref["ref_id"],
                        file=ref["file"],
                        role="environment",
                        environment_id=env_id,
                        purpose=ref.get("purpose", ""),
                        priority=ref.get("priority", 999),
                        display_name=ref.get("display_name", env_id),
                    ))

        return selections, selection_records

    # -- Full compilation -----------------------------------------------------

    def compile(
        self,
        panel_spec: dict[str, Any],
        surrounding_descriptions: list[str] | None = None,
        user_feedback: str | None = None,
        call_llm: Any = None,
    ) -> GenerationRequest:
        """
        Compile a PanelSpec into a GenerationRequest.

        Args:
            panel_spec: The PanelSpec dict (loaded from .panelspec.json).
            surrounding_descriptions: Brief descriptions of adjacent panels
                                      for continuity context.
            user_feedback: Optional human override for regeneration.
            call_llm: Optional callable to mock the Scene Prompt Generator.
                      Signature: (model, system_prompt, user_prompt) -> str.

        Returns:
            GenerationRequest ready for the Image Generation Backend.
        """
        panel_id = panel_spec["panel_id"]

        # -- Reference image selection (before prompt assembly for layer [8]) --
        selections, selection_records = self._select_references(panel_spec)

        # -- Layer [5]: Scene prompt (LLM call) --
        scene_prompt = self.scene_prompt_generator.generate(
            panel_spec=panel_spec,
            surrounding_descriptions=surrounding_descriptions,
            user_feedback=user_feedback,
            call_llm=call_llm,
        )

        # Update context store (no-op in v1)
        self.context_store.update_scene_context(panel_id, scene_prompt, {})

        # -- Assemble the full prompt string --
        layers: list[str] = []

        # [1] Style
        layer1 = self._layer_style(panel_spec)
        if layer1:
            layers.append(layer1)

        # [2] Shot + Mood
        layer2 = self._layer_shot_mood(panel_spec)
        if layer2:
            layers.append(layer2)

        # [3] Environment
        layer3 = self._layer_environment(panel_spec)
        if layer3:
            layers.append(layer3)

        # [4] Characters
        layer4 = self._layer_characters(panel_spec)
        if layer4:
            layers.append(layer4)

        # [5] Scene prompt
        layers.append(scene_prompt)

        # [6] Exclusions
        layer6 = self._layer_exclusions(panel_spec)
        if layer6:
            layers.append(f"Exclude: {layer6}")

        # [7] Negative space
        layer7 = self._layer_negative_space(panel_spec)
        if layer7:
            layers.append(layer7)

        # [8] Reference image descriptions
        layer8 = self._layer_reference_descriptions(selections)
        if layer8:
            layers.append(layer8)

        prompt = "\n\n".join(layers)

        # -- Aspect ratio selection --
        geo = panel_spec["panel_geometry"]
        size = select_aspect_ratio(geo["width_px"], geo["height_px"])

        # -- Build reference_images list for the Backend --
        reference_images: list[dict[str, str]] = []
        for sel in selection_records:
            # Resolve the file path relative to the project root
            if sel.role == "character":
                file_path = f"characters/{sel.file}"
            else:
                file_path = f"environments/{sel.file}"
            reference_images.append({
                "ref_id": sel.ref_id,
                "file": file_path,
                "role": sel.role,
            })

        # -- Build the GenerationRequest --
        ig = self.config.image_generation

        return GenerationRequest(
            panel_id=panel_id,
            model=ig.model,
            prompt=prompt,
            size=size,
            quality=ig.quality,
            thinking=ig.thinking,
            seed=ig.seed,
            reference_images=reference_images,
            panelspec_path=f"output/{panel_id}.panelspec.json",
            compiler_version=self.config.compiler_version,
            _scene_prompt=scene_prompt,
            _reference_selections=selection_records,
            _context_profile=self.config.scene_prompt.context_profile,
        )
